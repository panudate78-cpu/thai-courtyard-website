import type { RestaurantConfig } from "@/lib/restaurant";

export type LiveSeoPage = {
  path: string;
  label: string;
  metaTitle: string;
  metaDescription: string;
  structuredData: string[];
};

/** Mirrors the metadata published by the public pages, built from the live restaurant profile. */
export function buildLiveSeoPages(config: RestaurantConfig): LiveSeoPage[] {
  const place = config.address.locality ? ` in ${config.address.locality}` : "";
  return [
    {
      path: "/",
      label: "Home",
      metaTitle: `${config.name} | ${config.cuisine || "Restaurant"}${place}`,
      metaDescription: config.description,
      structuredData: ["Restaurant", "OrderAction", "ReserveAction"],
    },
    {
      path: "/menu",
      label: "Menu",
      metaTitle: `Menu | ${config.fullName}`,
      metaDescription: `The ${config.name} menu${place} — freshly prepared dishes with prices and dietary information. Order online for collection or book a table.`,
      structuredData: ["Menu", "BreadcrumbList"],
    },
    {
      path: "/order",
      label: "Order collection",
      metaTitle: `Order Online for Collection | ${config.fullName}`,
      metaDescription: `Order online for collection from ${config.name}${place}. Choose your dishes and collection time, then pay in the restaurant by cash or card.`,
      structuredData: ["BreadcrumbList"],
    },
    {
      path: "/book",
      label: "Book a table",
      metaTitle: `Book a Table | ${config.fullName}`,
      metaDescription: `Book a table at ${config.name}${place}. Send a reservation request online and we'll confirm by phone or email. Open ${config.hoursSummary}.`,
      structuredData: ["BreadcrumbList", "ReserveAction"],
    },
    {
      path: "/about",
      label: "About",
      metaTitle: `About Us | ${config.fullName}`,
      metaDescription: `The story of ${config.name}${place} — ${config.description}`,
      structuredData: ["BreadcrumbList"],
    },
    {
      path: "/contact",
      label: "Contact",
      metaTitle: `Contact & Opening Hours | ${config.fullName}`,
      metaDescription: `Find ${config.name} at ${config.addressLine}. Open ${config.hoursSummary}. Call ${config.phoneDisplay} or send us a message.`,
      structuredData: ["BreadcrumbList"],
    },
  ];
}

